package com.loops.forloop;

public class Alphabets {

	public static void main(String[] args) {
		for(char ch='a';ch<='z';ch++) {
			System.out.print(ch+" ");
		} 
		System.out.println();
		for(char ch='a';ch<='z';ch++) {
			if((ch =='a')||(ch =='e')||(ch =='i')||(ch =='o')||(ch =='u')){
				System.out.print(ch+" ");
				
			}
		} 

	}

}
